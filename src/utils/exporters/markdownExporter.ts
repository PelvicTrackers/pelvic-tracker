import type {
  SexualLogEntry,
  UrinaryLogEntry,
  BowelLogEntry,
  PatientNote,
  CustomMetricItem,
  AnatomyProfile
} from '../../types';
import {
  formatDateTime,
  getSexualActivityName,
  getEjaculationName,
  getUrinaryUrgencyLabel,
  CLINICAL_METRIC_LABELS
} from '../logFormatters';
import {
  getArousalMetricLabel,
  getClimaxMetricLabel,
  getSplintingLabel
} from '../../data/clinicalScales';

function formatNotesAndMetricsMarkdown(
  notes?: string,
  metricComments?: Record<string, string>,
  customMetrics?: CustomMetricItem[]
): string {
  const parts: string[] = [];
  if (notes && notes.trim().length > 0) {
    parts.push(notes.trim().replace(/\|/g, '/').replace(/\n/g, ' '));
  }

  if (metricComments) {
    const comments = Object.entries(metricComments).filter(([, v]) => v && v.trim().length > 0);
    for (const [k, v] of comments) {
      const label = CLINICAL_METRIC_LABELS[k] || k;
      const cleanV = v.trim().replace(/\|/g, '/').replace(/\n/g, ' ');
      parts.push(`[${label}: ${cleanV}]`);
    }
  }

  if (customMetrics && customMetrics.length > 0) {
    for (const cm of customMetrics) {
      const val = (cm.isNA || cm.value === null)
        ? 'N/A'
        : cm.scale === '1-10'
          ? `${cm.value}/10`
          : `${cm.value}%`;
      const cleanComment = cm.comment && cm.comment.trim()
        ? ` (${cm.comment.trim().replace(/\|/g, '/').replace(/\n/g, ' ')})`
        : '';
      const cleanName = cm.name.replace(/\|/g, '/');
      parts.push(`[${cleanName}: ${val}${cleanComment}]`);
    }
  }

  return parts.length > 0 ? parts.join(' ') : '-';
}

export function generateMarkdownReport(data: {
  sexual: SexualLogEntry[];
  urinary: UrinaryLogEntry[];
  bowel: BowelLogEntry[];
  notes: PatientNote[];
  patientInitials?: string;
  dateRangeLabel?: string;
  anatomyProfile?: AnatomyProfile;
}): string {
  const exportDate = formatDateTime(new Date().toISOString());
  const initials = data.patientInitials ? ` (Patient: ${data.patientInitials})` : '';

  let md = `# Pelvic Health Clinical Documentation Summary${initials}\n\n`;
  md += `**Export Timestamp:** ${exportDate}\n`;
  if (data.dateRangeLabel) {
    md += `**Date Filter Range:** ${data.dateRangeLabel}\n`;
  }
  md += `**Generated By:** Pelvic Trackers PWA (Local-First Offline Database)\n\n`;
  md += `---\n\n`;

  // 1. Sexual Function & Pelvic Pain
  const arousalCol = getArousalMetricLabel(data.anatomyProfile);
  const climaxCol = getClimaxMetricLabel(data.anatomyProfile);

  md += `## 1. Sexual Function & Pelvic Pain Diary (IPC Standard)\n\n`;
  if (data.sexual.length === 0) {
    md += `*No sexual health entries recorded during this tracking period.*\n\n`;
  } else {
    md += `| Date & Time | Activity | Position & Dur | Pain (Bef / Dur / Aft) | ${arousalCol} | Pleasure | ${climaxCol} | Clinical Notes & Scales |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;
    for (const e of data.sexual) {
      const dur = e.durationMinutes !== null ? `${e.durationMinutes}m` : 'N/A';
      const pos = e.position ? `${e.position.replace(/\|/g, '/')} (${dur})` : dur;
      const painStr = `${e.painBefore ?? 'N/A'} / ${e.painDuring ?? 'N/A'} / ${e.painAfter ?? 'N/A'}`;
      const arousalStr = e.erectionArousalScore !== null ? `${e.erectionArousalScore}%` : 'N/A';
      const pleasureStr = e.pleasureScore !== null ? `${e.pleasureScore}%` : 'N/A';
      const notesAndScales = formatNotesAndMetricsMarkdown(e.notes, e.metricComments, e.customMetrics);
      md += `| ${formatDateTime(e.timestamp)} | ${getSexualActivityName(e.activity)} | ${pos} | ${painStr} | ${arousalStr} | ${pleasureStr} | ${getEjaculationName(e.ejaculation, data.anatomyProfile)} | ${notesAndScales} |\n`;
    }
    md += `\n`;
  }

  // 2. Urinary / Bladder Diary
  md += `## 2. Urinary & Bladder Diary\n\n`;

  const voidEntries = data.urinary.filter(
    (u) => u.eventType === 'void' || u.eventType === 'combined' || (!u.eventType && (u.voidVolumeType || typeof u.voidVolumeMl === 'number' || typeof u.fluidIntakeAmountMl === 'number'))
  );
  const leakageEntries = data.urinary.filter(
    (u) => u.eventType === 'leakage' || u.eventType === 'combined' || (u.leakageType && u.leakageType !== 'none') || (u.leakageAmount && u.leakageAmount !== 'none')
  );

  md += `### 2.1 Urinary Voids & Fluid Intake\n\n`;
  if (voidEntries.length === 0) {
    md += `*No voiding records logged during this tracking period.*\n\n`;
  } else {
    md += `| Date & Time | Fluid Intake | Void Output | Stream | Urgency | Clinical Notes & Scales |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- | :--- |\n`;
    for (const u of voidEntries) {
      const intake = typeof u.fluidIntakeAmountMl === 'number' && u.fluidIntakeAmountMl > 0
        ? `${u.fluidIntakeAmountMl} mL (${u.fluidType})`
        : (u.fluidIntakeAmountMl === null ? 'N/A' : '-');
      const voidDesc = u.voidVolumeType === 'Measured'
        ? (u.voidVolumeMl !== null ? `${u.voidVolumeMl} mL` : 'N/A')
        : (u.voidVolumeType ?? 'N/A');
      const notesAndScales = formatNotesAndMetricsMarkdown(u.notes, u.metricComments, u.customMetrics);
      md += `| ${formatDateTime(u.timestamp)} | ${intake} | ${voidDesc} | ${u.voidStream ?? 'N/A'} | ${getUrinaryUrgencyLabel(u.urgencyLevel)} | ${notesAndScales} |\n`;
    }
    md += `\n`;
  }

  md += `### 2.2 Incontinence & Leakage Episodes\n\n`;
  if (leakageEntries.length === 0) {
    md += `*No incontinence episodes logged during this tracking period.*\n\n`;
  } else {
    md += `| Date & Time | Leak Type | Leak Amount | Activity / Trigger | Pad Status | Urgency | Clinical Notes & Scales |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;
    for (const u of leakageEntries) {
      const notesAndScales = formatNotesAndMetricsMarkdown(u.notes, u.metricComments, u.customMetrics);
      const activity = (u.leakageActivity || 'None reported').replace(/\|/g, '/');
      md += `| ${formatDateTime(u.timestamp)} | ${u.leakageType !== 'none' ? u.leakageType : 'None'} | ${u.leakageAmount !== 'none' ? u.leakageAmount : 'None'} | ${activity} | ${u.padUsage ?? 'N/A'} | ${getUrinaryUrgencyLabel(u.urgencyLevel)} | ${notesAndScales} |\n`;
    }
    md += `\n`;
  }

  // 3. Bowel Diary
  md += `## 3. Bowel & Defecation Diary (Bristol Stool Scale)\n\n`;
  if (data.bowel.length === 0) {
    md += `*No bowel movements recorded during this tracking period.*\n\n`;
  } else {
    md += `| Date & Time | Bristol Type | Straining (0-10) | Evacuation | Pain (B / D / A) | Leakage | Splinting / Assist | Clinical Notes & Scales |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;
    for (const b of data.bowel) {
      const bristolStr = b.bristolType !== null ? `Type ${b.bristolType}` : 'N/A';
      const strainStr = b.strainingLevel !== null ? `${b.strainingLevel}/10` : 'N/A';
      const painStr = `${b.painBefore ?? 'N/A'} / ${b.painDuring ?? 'N/A'} / ${b.painAfter ?? 'N/A'}`;
      const splintingDesc = b.posturalSplinting ? getSplintingLabel(b.posturalSplinting) : 'None';
      const notesAndScales = formatNotesAndMetricsMarkdown(b.notes, b.metricComments, b.customMetrics);
      md += `| ${formatDateTime(b.timestamp)} | ${bristolStr} | ${strainStr} | ${b.evacuationCompleteness ?? 'N/A'} | ${painStr} | ${b.accidentalLeakage ?? 'N/A'} | ${splintingDesc} | ${notesAndScales} |\n`;
    }
    md += `\n`;
  }

  // 4. Notes & PT Questions
  md += `## 4. Patient Symptoms, Flare-ups & PT Questions\n\n`;
  if (data.notes.length === 0) {
    md += `*No patient notes recorded.*\n\n`;
  } else {
    for (const n of data.notes) {
      md += `### [${n.category}] ${n.title ? n.title : formatDateTime(n.timestamp)}\n`;
      md += `**Date:** ${formatDateTime(n.timestamp)}\n\n`;
      md += `${n.content}\n\n`;
    }
  }

  // 5. Clinical Reference & Scale Legend
  md += `## 5. Clinical Reference & Scale Legend\n\n`;

  md += `### 5.1 Pain Scoring (0–10 NRS) & Timing\n`;
  md += `- **B / D / A:** Pain **Before**, **During**, and **After** activity.\n`;
  md += `- **NRS Scale:** **0** = No pain (clinically significant baseline) | **1–3** = Mild | **4–6** = Moderate | **7–10** = Severe.\n\n`;

  md += `### 5.2 Sexual Function & Activity Codes\n`;
  md += `| Code | Activity / Meaning | Clinical Detail |\n`;
  md += `| :--- | :--- | :--- |\n`;
  md += `| **M** | Masturbation | Neutral Baseline |\n`;
  md += `| **PVI** | Penile-Vaginal Intercourse | Penetrative |\n`;
  md += `| **RVI** | Receptive Vaginal Intercourse | Receptive partner |\n`;
  md += `| **PAI** | Penile-Anal Intercourse | Penetrative |\n`;
  md += `| **RAI** | Receptive Anal Intercourse | Receptive partner |\n`;
  md += `| **Other** | Other Intimacy | Non-penetrative intimacy / manual stimulation |\n\n`;

  md += `### 5.3 Climax / Orgasm & Ejaculation Codes\n`;
  md += `| Code | Status | Clinical Description |\n`;
  md += `| :--- | :--- | :--- |\n`;
  md += `| **N** | Normal | Comfortable & expected timing (ejaculation / climax) |\n`;
  md += `| **E** | Early | Premature or rapid climax / ejaculation |\n`;
  md += `| **D** | Delayed | Extended effort required to reach climax |\n`;
  md += `| **A** | Absent | Anorgasmia / dry / unable to climax |\n`;
  md += `| **P** | Painful | Pelvic, perineal, or urethral discomfort on orgasm/climax |\n\n`;

  md += `### 5.4 Urinary Urgency & Incontinence Scale\n`;
  md += `| Level | Urgency Definition |\n`;
  md += `| :--- | :--- |\n`;
  md += `| **Level 0 (None)** | Normal sensation, can defer comfortably |\n`;
  md += `| **Level 1 (Mild)** | First sensation of fullness, easy to hold |\n`;
  md += `| **Level 2 (Moderate)** | Strong desire, must empty within minutes |\n`;
  md += `| **Level 3 (Severe)** | Sudden uncontrollable urge, fear of leakage |\n\n`;
  md += `- **Leakage Amounts:** Drops (Few Drops), Moderate (Moderate Wetness), Soaked (Heavy / Saturated).\n`;
  md += `- **Pad Statuses:** Dry (Pad remains dry), Damp (Light dampness), Wet (Noticeably wet), Replaced (Pad changed during period).\n\n`;

  md += `### 5.5 Bristol Stool Form Scale (BSFS)\n`;
  md += `| Type | Category | Stool Description |\n`;
  md += `| :--- | :--- | :--- |\n`;
  md += `| **Type 1** | Constipation | Separate hard lumps, like nuts (hard to pass) |\n`;
  md += `| **Type 2** | Constipation | Sausage-shaped, but lumpy and firm |\n`;
  md += `| **Type 3** | Normal | Like a sausage with cracks on its surface |\n`;
  md += `| **Type 4** | Normal (Ideal) | Smooth and soft, like a sausage or snake |\n`;
  md += `| **Type 5** | Normal | Soft blobs with clear-cut edges (passed easily) |\n`;
  md += `| **Type 6** | Diarrhea / Urgent | Fluffy pieces with ragged edges, a mushy stool |\n`;
  md += `| **Type 7** | Diarrhea / Urgent | Entirely liquid, watery, no solid pieces |\n\n`;

  md += `### 5.6 Bowel Assistance & Postural Splinting\n`;
  md += `- **Squatty Potty:** Footstool elevating knees above hips to relax the puborectalis muscle.\n`;
  md += `- **Manual Splinting:** Manual perineal or posterior vaginal wall pressure support during evacuation.\n`;
  md += `- **Both:** Footstool posture combined with manual perineal support.\n\n`;

  return md;
}
